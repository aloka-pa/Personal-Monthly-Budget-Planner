-- =========================================================
-- PERSONAL MONTHLY BUDGET PLANNER
-- Supabase database setup
-- =========================================================


-- =========================================================
-- 1. PROFILES
-- Stores the user's profile-card information
-- =========================================================

create table if not exists public.profiles (
    user_id uuid primary key
        references auth.users(id)
        on delete cascade,

    full_name text not null default '',
    designation text not null default '',
    company text not null default '',

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);


-- =========================================================
-- 2. CATEGORIES
-- user_id = null means it is a predefined category
-- user_id contains a UUID when it is a custom category
-- =========================================================

create table if not exists public.categories (
    id bigint generated by default as identity primary key,

    user_id uuid
        references auth.users(id)
        on delete cascade,

    name text not null,
    created_at timestamptz not null default now(),

    constraint category_name_not_empty
        check (length(trim(name)) > 0)
);


-- Prevent duplicate predefined categories
create unique index if not exists unique_default_category_name
on public.categories (lower(name))
where user_id is null;


-- Prevent a user from creating duplicate custom categories
create unique index if not exists unique_user_category_name
on public.categories (user_id, lower(name))
where user_id is not null;


-- =========================================================
-- 3. MONTHLY INCOMES
-- One income value per user per month
-- The month must always be the first day of the month
-- Example: 2026-07-01
-- =========================================================

create table if not exists public.monthly_incomes (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references auth.users(id)
        on delete cascade,

    month date not null,
    amount numeric(12,2) not null,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint monthly_income_amount_valid
        check (amount >= 0),

    constraint month_must_be_first_day
        check (month = date_trunc('month', month)::date),

    constraint one_income_per_user_per_month
        unique (user_id, month)
);


-- =========================================================
-- 4. EXPENSES
-- Stores each expense with date and time
-- =========================================================

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references auth.users(id)
        on delete cascade,

    category_id bigint not null
        references public.categories(id)
        on delete restrict,

    amount numeric(12,2) not null,
    expense_datetime timestamptz not null default now(),

    description text,
    is_recurring boolean not null default false,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint expense_amount_must_be_positive
        check (amount > 0),

    constraint description_length_limit
        check (
            description is null
            or length(description) <= 500
        )
);


-- Useful indexes for monthly reports and comparisons
create index if not exists expenses_user_datetime_index
on public.expenses (user_id, expense_datetime desc);

create index if not exists expenses_category_index
on public.expenses (category_id);

create index if not exists monthly_income_user_month_index
on public.monthly_incomes (user_id, month);


