-- =========================================================
-- 6. AUTOMATIC updated_at FUNCTION
-- =========================================================

create or replace function public.update_updated_at_column()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;


drop trigger if exists update_profiles_updated_at
on public.profiles;

create trigger update_profiles_updated_at
before update on public.profiles
for each row
execute function public.update_updated_at_column();


drop trigger if exists update_monthly_incomes_updated_at
on public.monthly_incomes;

create trigger update_monthly_incomes_updated_at
before update on public.monthly_incomes
for each row
execute function public.update_updated_at_column();


drop trigger if exists update_expenses_updated_at
on public.expenses;

create trigger update_expenses_updated_at
before update on public.expenses
for each row
execute function public.update_updated_at_column();


-- =========================================================
-- 7. CREATE PROFILE AUTOMATICALLY AFTER SIGN-UP
-- =========================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (
        user_id,
        full_name,
        designation,
        company
    )
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        coalesce(new.raw_user_meta_data ->> 'designation', ''),
        coalesce(new.raw_user_meta_data ->> 'company', '')
    );

    return new;
end;
$$;


drop trigger if exists on_auth_user_created
on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();


