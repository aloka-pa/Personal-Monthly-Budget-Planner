drop policy if exists "Users can create their own expenses"
on public.expenses;

create policy "Users can create their own expenses"
on public.expenses
for insert
to authenticated
with check (
    (select auth.uid()) = user_id
    and exists (
        select 1
        from public.categories
        where categories.id = expenses.category_id
          and (
              categories.user_id is null
              or categories.user_id = (select auth.uid())
          )
    )
);


drop policy if exists "Users can update their own expenses"
on public.expenses;

create policy "Users can update their own expenses"
on public.expenses
for update
to authenticated
using ((select auth.uid()) = user_id)
with check (
    (select auth.uid()) = user_id
    and exists (
        select 1
        from public.categories
        where categories.id = expenses.category_id
          and (
              categories.user_id is null
              or categories.user_id = (select auth.uid())
          )
    )
);


